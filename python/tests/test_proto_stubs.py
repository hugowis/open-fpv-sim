"""The committed Python stubs (`python/ofs/v1/sim_pb2*.py`) describe the same protocol as `proto/ofs/v1/sim.proto`.

They are regenerated by hand (`docs/dev-setup.md`); a proto edit with no regeneration would leave the client
silently ignoring the new field. The descriptors are compared, not the generated text, so the check does not depend on
which `grpcio-tools` version wrote the stubs."""
import pytest
from google.protobuf import descriptor_pb2

from conftest import REPO

protoc = pytest.importorskip("grpc_tools.protoc")


def _without_json_names(message):
    """protoc fills `json_name` into a descriptor set; the descriptor embedded in generated code leaves it out."""
    for field in message.field:
        field.ClearField("json_name")
    for nested in message.nested_type:
        _without_json_names(nested)


def test_the_committed_stubs_match_the_proto(tmp_path):
    from ofs.v1 import sim_pb2

    out = tmp_path / "sim.desc"
    status = protoc.main(["protoc", f"-I{REPO / 'proto'}", f"--descriptor_set_out={out}", str(REPO / "proto" / "ofs" / "v1" / "sim.proto")])
    assert status == 0, "protoc could not compile proto/ofs/v1/sim.proto"
    compiled = descriptor_pb2.FileDescriptorSet.FromString(out.read_bytes()).file[0]
    for message in compiled.message_type:
        _without_json_names(message)
    committed = descriptor_pb2.FileDescriptorProto.FromString(sim_pb2.DESCRIPTOR.serialized_pb)
    assert compiled == committed, (
        "python/ofs/v1 is out of date with proto/ofs/v1/sim.proto; regenerate it with the command in docs/dev-setup.md"
    )


def test_the_stub_knows_the_worlds_meshes():
    from ofs.v1 import sim_pb2

    mesh = sim_pb2.Mesh(name="hall", path="/w/assets/hall.glb", position_ned_m=sim_pb2.Vec3(x=30.0), heading_deg=90.0, digest=2**63 + 5)
    back = sim_pb2.World.FromString(sim_pb2.World(name="w", meshes=[mesh]).SerializeToString())
    assert back.meshes[0] == mesh and back.meshes[0].digest == 2**63 + 5
    assert not sim_pb2.World().meshes
