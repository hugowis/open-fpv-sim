ATTRIBUTION = "© OpenStreetMap contributors (ODbL 1.0, https://www.openstreetmap.org/copyright)"


class BuildError(Exception):
    """The recipe is valid but the site cannot be built; args[0] lists the problems, one per line."""


@dataclass
class BuildReport:
    footprints_used: int = 0
    skipped: dict[str, int] = field(default_factory=dict)  # footprints left out, by reason
    landmarks: int = 0
    triangles: int = 0
    materials: list[str] = field(default_factory=list)  # used by at least one triangle, sorted
    warnings: list[str] = field(default_factory=list)
    world_path: Path | None = None
    glb_path: Path | None = None

    def __str__(self):
        skipped = ", ".join(f"{k}={v}" for k, v in sorted(self.skipped.items())) or "none"
        lines = [f"{self.footprints_used} footprints, {self.landmarks} landmarks, {self.triangles} triangles",
                 f"skipped: {skipped}", f"materials: {', '.join(self.materials)}"]
        lines += [f"warning: {w}" for w in self.warnings]
        lines += [f"wrote {p}" for p in (self.world_path, self.glb_path) if p]
        return "\n".join(lines)


def _header(recipe_path: Path, world_dir: Path) -> str:
    try:
        rel = Path(os.path.relpath(recipe_path, world_dir)).as_posix()
    except ValueError:  # another drive on Windows
        rel = recipe_path.name
    return (f"# Generated by sitegen from {rel}\n# generated - edit the recipe, not this file\n# {ATTRIBUTION}\n"
            "# all values are estimates\n\n")


def build_site(recipe_path: Path, out_dir: Path | None = None) -> BuildReport:
    """Writes the .glb and the world file named by the recipe, or under out_dir with the same layout (tests)."""
    recipe_path = Path(recipe_path)
    recipe = load_recipe(recipe_path)
    site, rep, errors = recipe.site, BuildReport(landmarks=len(recipe.landmarks)), []
    for k in ("meshes", "materials"):
        if k in recipe.world:
            raise BuildError(f"world.{k}: sitegen writes this table, take it out of [world]")
    try:
        ways = osm.read_snapshot(site.snapshot_path)
    except ValueError as e:
        raise BuildError(str(e)) from None

    proj, mb = Projection(*site.origin), MeshBuilder()
    over = {f.id: (i, f) for i, f in enumerate(recipe.footprints)}
    for fid in sorted(set(over) - {w.id for w in ways}):
        rep.warnings.append(f"footprints[{over[fid][0]}].id: {fid} is not in the snapshot")

    def skip(reason):
        rep.skipped[reason] = rep.skipped.get(reason, 0) + 1

    def skip_with_openings(reason, fid, o):  # the author wrote the openings, so say they went unused
        skip(reason)
        if o and o.openings:
            rep.warnings.append(f"footprint {fid}: openings ignored, skipped as {reason}")

    seen = set()
    for w in sorted(ways, key=lambda w: w.id):  # sorted stably: the first of a duplicated id wins
        if w.id in seen:
            skip("duplicate_id")
            continue
        seen.add(w.id)
        i, o = over.get(w.id, (None, None))
        if o and o.skip:
            skip_with_openings("recipe_skip", w.id, o)
            continue
        ring = normalize_ring([proj.to_ned(*p) for p in w.ring])
        if ring is None:
            skip_with_openings("bad_ring", w.id, o)
            continue
        # Touching the extent is enough: a long building (a 600 m turbine hall) stays whole when only part of it is inside.
        (n0, n1), (e0, e1) = ((min(v), max(v)) for v in zip(*ring))
        hn, he = site.half_extent_m
        if n0 > hn or n1 < -hn or e0 > he or e1 < -he:
            skip_with_openings("outside_extent", w.id, o)
            continue
        material = o.material if o and o.material else "building"
        if material not in recipe.colors:
            errors.append(f"footprints[{i}].material: {material!r} has no colour in [colors]")
            continue
        height = o.height_m if o and o.height_m is not None else osm.height_of(
            w.tags, recipe.defaults.building_height_m, recipe.defaults.level_height_m)
        part = MeshBuilder()  # extrude can fail after adding the walls
        if o and o.openings:  # the author wrote the opening, so one that does not fit is an error, not a skip
            try:
                walls(part, ring, height, material, o.openings, roof=True)
            except ValueError as e:
                errors.append(f"footprint {w.id}.{e}")
                continue
            mb.extend(part)
            rep.footprints_used += 1
            continue
        try:
            extrude(part, ring, height, material)
        except ValueError:
            skip("extrude_error")
            continue
        mb.extend(part)
        rep.footprints_used += 1

    for lm in recipe.landmarks:
        before = len(mb.triangles)
        try:
            build_landmark(mb, lm, proj)
        except ValueError as e:
            raise BuildError(str(e)) from None
        for m in sorted({t[3] for t in mb.triangles[before:]} - recipe.colors.keys()):
            errors.append(f"landmarks[{lm.name}]: material {m!r} has no colour in [colors]")
    if errors:
        raise BuildError("\n".join(errors))
    if not mb.triangles:
        raise BuildError(f"no geometry: no footprint survived ({rep.skipped or 'the snapshot has none'}) and the recipe has no landmarks")

    rep.triangles, rep.materials = len(mb.triangles), sorted({t[3] for t in mb.triangles})
    listed = recipe.materials
    rep.warnings += [f"material {m!r} is used but not in [[materials]]; it loses 0 dB" for m in rep.materials if m not in {x.name for x in listed}]
    rep.warnings += [f"material {m.name!r} is in [[materials]] but no triangle uses it; left out of the world file"
                     for m in listed if m.name not in rep.materials]

    world = {"schema_version": 1, "name": site.name, **recipe.world}
    world["meshes"] = [{"name": site.name, "file": recipe.glb_rel}]
    world["materials"] = [{"name": m.name, "rf_loss_db": m.rf_loss_db} for m in listed if m.name in rep.materials]
    glb = write_glb({site.name: mb}, {m: recipe.colors[m] for m in rep.materials})

    world_path, glb_path = recipe.world_path, recipe.glb_path
    if out_dir is not None:  # a world path that climbs out of the recipe's directory also climbs out of out_dir
        world_path = Path(out_dir) / os.path.relpath(world_path, recipe_path.parent)
        glb_path = world_path.parent / recipe.glb_rel
    try:
        text = _header(recipe_path, recipe.world_path.parent) + dumps(world)
    except TypeError as e:  # e.g. a TOML date in [world]
        raise BuildError(f"world: {e}") from None
    # Everything is validated and rendered before the first byte is written.
    claimed = {"the recipe": recipe_path, "the snapshot": site.snapshot_path, "output.world": world_path}
    for name, p in (("output.world", world_path), ("output.glb", glb_path)):
        for other, q in claimed.items():
            if other != name and p.resolve() == q.resolve():
                raise BuildError(f"{name} and {other} are the same file ({p}); refusing to overwrite it")
    _write_all([(glb_path, glb), (world_path, text.encode("utf-8"))])
    rep.world_path, rep.glb_path = world_path, glb_path
    return rep


def describe_walls(recipe_path: Path, way_id: int) -> list[str]:
    """One line per wall of the footprint's normalised ring, the indices a `openings` entry uses."""
    recipe = load_recipe(Path(recipe_path))
    try:
        ways = osm.read_snapshot(recipe.site.snapshot_path)
    except ValueError as e:
        raise BuildError(str(e)) from None
    way = next((w for w in sorted(ways, key=lambda w: w.id) if w.id == way_id), None)  # the first of a duplicated id, as build does
    if way is None:
        raise BuildError(f"way {way_id} is not in {recipe.site.snapshot}")
    proj = Projection(*recipe.site.origin)
    ring = normalize_ring([proj.to_ned(*p) for p in way.ring])
    if ring is None:
        raise BuildError(f"way {way_id}: not a usable footprint")
    lines = []
    for i, (p0, p1) in enumerate(zip(ring, ring[1:] + ring[:1])):
        dn, de = p1[0] - p0[0], p1[1] - p0[1]
        bearing = round(math.degrees(math.atan2(de, dn)) + 90) % 360  # counter-clockwise ring: outside is right of the edge
        lines.append(f"{i:3d}  {p0[0]:9.1f}  {p0[1]:9.1f}  {math.hypot(dn, de):8.1f}  {bearing:3d}")
    return lines


def _write_all(files: list[tuple[Path, bytes]]) -> None:
    """Temp files first, then renames, so a failed write leaves the old outputs alone."""
    tmps = []
    try:
        for p, data in files:
            p.parent.mkdir(parents=True, exist_ok=True)
            tmps.append(p.with_name(p.name + ".tmp"))
            tmps[-1].write_bytes(data)
        for (p, _), t in zip(files, tmps):
            os.replace(t, p)
    except OSError as e:
        raise BuildError(f"cannot write {e.filename or files[0][0]}: {e.strerror or e}") from None
    finally:
        for t in tmps:
            t.unlink(missing_ok=True)
